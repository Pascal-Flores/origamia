# Solution de l'exercice 180 - L'échelle de la cabane
# Le programme reste développé : aucune boucle.

from turtle import *

# Deux montants qui dépassent au-dessus et au-dessous des barreaux.
penup()
goto(0, -110)
pendown()
goto(0, 110)
penup()
goto(80, -110)
pendown()
goto(80, 110)

# Six barreaux. Le motif forward(80) / backward(80) est répété six fois.
penup()
goto(0, -80)
pendown()
forward(80)
backward(80)
penup()
goto(0, -48)
pendown()
forward(80)
backward(80)
penup()
goto(0, -16)
pendown()
forward(80)
backward(80)
penup()
goto(0, 16)
pendown()
forward(80)
backward(80)
penup()
goto(0, 48)
pendown()
forward(80)
backward(80)
penup()
goto(0, 80)
pendown()
forward(80)
backward(80)
